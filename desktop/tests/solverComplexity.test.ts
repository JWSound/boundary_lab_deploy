import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { loadSpeakerPackage } from "../src/io/speakerPackage";
import { estimateSolverComplexity, formatMemoryRange } from "../src/model/solverComplexity";
import type { RigidMeshAsset } from "../src/model/types";
const bytes = readFileSync("library/S218BP_LOD.blabsp");
const pkg = loadSpeakerPackage(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer, "S218BP_LOD.blabsp");
const source = { packageId: pkg.id, muted: true };
const boundary = estimateSolverComplexity([pkg], [source, source], [], [], "boundary", "cpu");
assert.equal(boundary.boundaryUnknowns, 2580, "Count every physical instance from the solver mesh, including muted instances");
assert.equal(boundary.reducedStates, 0);
const coupled = estimateSolverComplexity([pkg], [source, source], [], [], "coupled", "cpu");
assert.equal(coupled.reducedStates, 256, "32 states per sector × 4 sectors × 2 instances");
assert.equal(coupled.boundaryUnknowns, boundary.boundaryUnknowns, "Reduced states are not added to the exterior system");
assert.ok(coupled.memory!.system.maximum > boundary.memory!.system.maximum);
const rigid = { id: "stage", vertexCount: 8, triangleCount: 12 } as RigidMeshAsset;
const withRigid = estimateSolverComplexity([pkg], [source], [rigid], [{assetId:"stage"},{assetId:"stage"}], "boundary", "cpu");
assert.equal(withRigid.boundaryUnknowns, 1306);
const other = {...pkg,id:"other"};
assert.equal(estimateSolverComplexity([pkg,other],[source,{packageId:"other"}],[],[],"coupled","cpu").reducedStates,256);
const one = estimateSolverComplexity([pkg],[source],[],[],"boundary","cpu");
assert.ok(boundary.memory!.system.minimum > 3 * one.memory!.system.minimum, "Dense matrix memory grows approximately quadratically");
const sampled = estimateSolverComplexity([pkg],[source],[],[],"boundary","cpu",100000);
assert.equal(sampled.boundaryUnknowns,one.boundaryUnknowns);
assert.ok(sampled.memory!.system.maximum > one.memory!.system.maximum);
const gpu = estimateSolverComplexity([pkg],[source],[],[],"coupled","cuda");
assert.ok(gpu.memory!.gpu!.maximum >= gpu.memory!.gpu!.minimum);
const rocm = estimateSolverComplexity([pkg],[source],[],[],"coupled","rocm");
assert.equal(rocm.memory!.unified, false);
assert.ok(rocm.memory!.gpu!.minimum > gpu.memory!.gpu!.minimum, "ROCm retains operators and F64 factors instead of CUDA direct-system storage");
assert.ok(rocm.memory!.system.minimum > 0);
const rocmArray = estimateSolverComplexity([pkg],[source,source],[],[],"coupled","rocm");
assert.ok(rocmArray.memory!.gpu!.minimum > 3 * rocm.memory!.gpu!.minimum);
assert.equal(estimateSolverComplexity([pkg],[source],[],[],"coupled","metal").memory!.unified,true);
assert.equal(estimateSolverComplexity([], [source], [], [], "boundary", "cpu").boundaryUnknowns,null);
assert.equal(estimateSolverComplexity([pkg], [source], [], [{assetId:"missing"}], "boundary", "cpu").memory,null);
const unsupported={...pkg,manifest:{...pkg.manifest,files:{...pkg.manifest.files,coupled_model:{path:"exact.json",representation:"exact"}}}};
assert.equal(estimateSolverComplexity([unsupported],[source],[],[],"coupled","cpu").memory,null);
assert.equal(estimateSolverComplexity([unsupported],[source],[],[],"coupled","cpu").reducedStates,null);
assert.equal(estimateSolverComplexity([pkg],[source],[],[],"boundary",null).memory,null);
assert.equal(formatMemoryRange(estimateSolverComplexity([],[],[],[],"boundary","cpu").memory!.system),"0 MiB");
console.log("Solver complexity passed: real package counts, instances, rigid meshes, reduced states, backend ranges, missing metadata and evaluation grids.");
